-- Postojeći projekti s otvorenim using(true) policyjima: pokreni supabase_rls_harden.sql
-- Zatim: Table Editor (provjeri cards / price_history / portfolio / watchlist)
-- Ako API i dalje ne vidi tablice: Settings → API → Reload schema cache
-- ili pokreni zadnji red: NOTIFY pgrst, 'reload schema';
--
-- Ključevi: SUPABASE_ANON_KEY = UI login + portfolio/watchlist (RLS).
--           SUPABASE_KEY (service_role) = nightly/backfill/catalog sync only.

create table if not exists public.cards (
    id text primary key,
    name text,
    supertype text,
    rarity text,
    set_name text,
    market_price double precision,
    pokewallet_id text,
    tcgplayer_id text,
    image_url text
);

alter table public.cards add column if not exists tcgplayer_id text;

create table if not exists public.price_history (
    id bigint generated by default as identity primary key,
    card_id text not null references public.cards (id) on delete cascade,
    price double precision not null,
    date date not null
);

create index if not exists price_history_card_id_idx on public.price_history (card_id);
create index if not exists price_history_date_idx on public.price_history (date);

create table if not exists public.portfolio (
    id bigint generated by default as identity primary key,
    user_id uuid references auth.users (id) on delete cascade,
    card_id text not null references public.cards (id) on delete cascade,
    quantity integer not null check (quantity >= 1),
    purchase_price double precision not null check (purchase_price > 0),
    purchase_date text not null,
    condition text default 'NM',
    printing text default 'Normal',
    grade text,
    status text not null default 'open',
    sale_price double precision,
    sale_date text
);

-- Existing projects: add user_id if the table already existed without it.
alter table public.portfolio add column if not exists user_id uuid references auth.users (id) on delete cascade;
alter table public.portfolio add column if not exists condition text default 'NM';
alter table public.portfolio add column if not exists printing text default 'Normal';
alter table public.portfolio add column if not exists grade text;
alter table public.portfolio add column if not exists status text not null default 'open';
alter table public.portfolio add column if not exists sale_price double precision;
alter table public.portfolio add column if not exists sale_date text;

create index if not exists portfolio_card_id_idx on public.portfolio (card_id);
create index if not exists portfolio_user_id_idx on public.portfolio (user_id);

-- Watchlist: track cards without cost basis.
create table if not exists public.watchlist (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users (id) on delete cascade,
    card_id text not null references public.cards (id) on delete cascade,
    created_at timestamptz not null default now(),
    unique (user_id, card_id)
);

create index if not exists watchlist_user_id_idx on public.watchlist (user_id);

alter table public.cards enable row level security;
alter table public.price_history enable row level security;
alter table public.portfolio enable row level security;
alter table public.watchlist enable row level security;

-- Catalog: public read for anon + authenticated.
-- Writes go through service_role (bypasses RLS) from nightly/backfill only.
drop policy if exists "service_read_cards" on public.cards;
drop policy if exists "service_write_cards" on public.cards;
drop policy if exists "anon_read_cards" on public.cards;
create policy "anon_read_cards" on public.cards
  for select to anon, authenticated using (true);

drop policy if exists "service_read_price_history" on public.price_history;
drop policy if exists "service_write_price_history" on public.price_history;
drop policy if exists "anon_read_price_history" on public.price_history;
create policy "anon_read_price_history" on public.price_history
  for select to anon, authenticated using (true);

-- Portfolio / watchlist: ONLY own rows via JWT (auth.uid()).
-- Do NOT add using(true) policies — those expose every user's lots to anon.
-- service_role still bypasses RLS for local AUTH_DISABLED / admin scripts.
drop policy if exists "service_read_portfolio" on public.portfolio;
drop policy if exists "service_write_portfolio" on public.portfolio;
drop policy if exists "portfolio_select_own" on public.portfolio;
create policy "portfolio_select_own" on public.portfolio
  for select to authenticated using (auth.uid() = user_id);
drop policy if exists "portfolio_insert_own" on public.portfolio;
create policy "portfolio_insert_own" on public.portfolio
  for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "portfolio_update_own" on public.portfolio;
create policy "portfolio_update_own" on public.portfolio
  for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "portfolio_delete_own" on public.portfolio;
create policy "portfolio_delete_own" on public.portfolio
  for delete to authenticated using (auth.uid() = user_id);

drop policy if exists "service_read_watchlist" on public.watchlist;
drop policy if exists "service_write_watchlist" on public.watchlist;
drop policy if exists "watchlist_select_own" on public.watchlist;
create policy "watchlist_select_own" on public.watchlist
  for select to authenticated using (auth.uid() = user_id);
drop policy if exists "watchlist_insert_own" on public.watchlist;
create policy "watchlist_insert_own" on public.watchlist
  for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "watchlist_update_own" on public.watchlist;
create policy "watchlist_update_own" on public.watchlist
  for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "watchlist_delete_own" on public.watchlist;
create policy "watchlist_delete_own" on public.watchlist
  for delete to authenticated using (auth.uid() = user_id);

grant usage on schema public to postgres, anon, authenticated, service_role;
grant all on table public.cards to postgres, anon, authenticated, service_role;
grant all on table public.price_history to postgres, anon, authenticated, service_role;
grant all on table public.portfolio to postgres, anon, authenticated, service_role;
grant all on table public.watchlist to postgres, anon, authenticated, service_role;
grant usage, select on all sequences in schema public to postgres, anon, authenticated, service_role;

