-- Kestrel Pro entitlements from Creem (or manual grants).
-- Run once in Supabase → SQL Editor → Run.
-- API uses service_role to upsert; clients never write this table.

create table if not exists public.pro_entitlements (
    id bigint generated by default as identity primary key,
    email text not null,
    user_id uuid references auth.users (id) on delete set null,
    status text not null default 'active'
        check (status in ('active', 'canceled', 'past_due', 'expired')),
    source text not null default 'creem',
    creem_customer_id text,
    creem_subscription_id text,
    creem_product_id text,
    creem_order_id text,
    creem_checkout_id text,
    metadata jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- Emails are always stored lowercased by the API.
create unique index if not exists pro_entitlements_email_uidx
    on public.pro_entitlements (email);

create index if not exists pro_entitlements_user_id_idx
    on public.pro_entitlements (user_id);

create index if not exists pro_entitlements_status_idx
    on public.pro_entitlements (status);

alter table public.pro_entitlements enable row level security;

-- No anon/authenticated policies: service_role only (bypasses RLS).
drop policy if exists "deny_all_pro_entitlements" on public.pro_entitlements;

notify pgrst, 'reload schema';
